def find(tbl, city, eq, n=1):
    return next(r for r in tbl if r["city"] == city and r["eq"] == eq and r["n"] == n)


def e(city, eq, n=1):
    return R.score(find(T4, city, eq, n), G4, threshold=30.0)[0]


